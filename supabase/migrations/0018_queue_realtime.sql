-- ============================================================
-- Migration 0018: تفعيل Supabase Realtime على طابور الانتظار
-- ============================================================
-- بدل ما شاشة الطابور تسأل السيرفر كل 5 ثواني (polling)، دلوقتي
-- بنفعّل Realtime على الجدول ده بس، عشان السيرفر "يبلّغ" المتصفح
-- تلقائيًا لما يحصل تغيير فعلي (إضافة عيان، بدء كشف، تخليصه...).
-- الميزة دي جزء من خطة Supabase الحالية أصلاً، مفيش أي تكلفة إضافية.
--
-- ملحوظة: الـ RLS الموجودة على الجدول (staff_all_queue) بتتطبق على
-- إشعارات Realtime برضه، يعني الموظف مش هياخد إشعار إلا لو أصلاً
-- عنده صلاحية يشوف الصف ده - مفيش أي تغيير في مين يشوف إيه.
-- ============================================================

-- بنتأكد الأول إن الجدول مش مضاف قبل كده، عشان لو الملف اتشغّل غلط
-- مرتين ميحصلش error ويوقف باقي التسليم
do $$
begin
  if not exists (
    select 1 from pg_publication_tables
    where pubname = 'supabase_realtime' and tablename = 'queue_entries'
  ) then
    alter publication supabase_realtime add table queue_entries;
  end if;
end $$;
